package scaffold

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/tankibaj/server-them/internal/manifest"
)

func TestCreateSplitViteFastAPIManifest(t *testing.T) {
	d := t.TempDir()
	mustMkdir(t, filepath.Join(d, "frontend"))
	mustWrite(t, filepath.Join(d, "frontend", "package.json"), `{"scripts":{"dev":"vite"},"devDependencies":{"vite":"latest"}}`)
	mustMkdir(t, filepath.Join(d, "backend", "app"))
	mustWrite(t, filepath.Join(d, "backend", "requirements.txt"), "fastapi\nuvicorn\n")
	mustWrite(t, filepath.Join(d, "backend", "app", "main.py"), "from fastapi import FastAPI\napp = FastAPI()\n")
	mustMkdir(t, filepath.Join(d, "backend", ".venv", "bin"))
	mustWrite(t, filepath.Join(d, "backend", ".venv", "bin", "uvicorn"), "")
	if e := os.Chmod(filepath.Join(d, "backend", ".venv", "bin", "uvicorn"), 0755); e != nil {
		t.Fatal(e)
	}
	mustWrite(t, filepath.Join(d, "backend", ".env"), "SECRET=not-read\n")
	file, e := Create(d)
	if e != nil {
		t.Fatal(e)
	}
	b, e := os.ReadFile(file)
	if e != nil {
		t.Fatal(e)
	}
	got := string(b)
	if _, e = manifest.Load(file); e != nil {
		t.Fatalf("generated manifest is invalid: %v", e)
	}
	for _, want := range []string{"# Generated by serve-them init.", "web: ./frontend", "api:\n  path: ./backend", "run: ./.venv/bin/uvicorn app.main:app --host 127.0.0.1 --port ${PORT} --reload", "# Path is passed through; Serve Them never reads this file.", "ENV_FILE: ./.env"} {
		if !strings.Contains(got, want) {
			t.Fatalf("manifest missing %q:\n%s", want, got)
		}
	}
}

func TestCreateRootNodeManifest(t *testing.T) {
	d := t.TempDir()
	mustWrite(t, filepath.Join(d, "package.json"), `{"scripts":{"dev":"vite"},"devDependencies":{"vite":"latest"}}`)
	file, e := Create(d)
	if e != nil {
		t.Fatal(e)
	}
	b, _ := os.ReadFile(file)
	if !strings.Contains(string(b), "web: .") {
		t.Fatalf("unexpected manifest: %s", b)
	}
}

func TestCreateNeverOverwrites(t *testing.T) {
	d := t.TempDir()
	file := filepath.Join(d, "serve.yaml")
	mustWrite(t, file, "web: keep\n")
	if _, e := Create(d); e == nil || !strings.Contains(e.Error(), "already exists") {
		t.Fatalf("expected protection error, got %v", e)
	}
	b, _ := os.ReadFile(file)
	if string(b) != "web: keep\n" {
		t.Fatal("existing manifest changed")
	}
}

func TestCreateRejectsUnsupportedDirectory(t *testing.T) {
	if _, e := Create(t.TempDir()); e == nil || !strings.Contains(e.Error(), "unable to detect") {
		t.Fatalf("expected detection error, got %v", e)
	}
}

func mustMkdir(t *testing.T, path string) {
	t.Helper()
	if e := os.MkdirAll(path, 0755); e != nil {
		t.Fatal(e)
	}
}
func mustWrite(t *testing.T, path, body string) {
	t.Helper()
	if e := os.WriteFile(path, []byte(body), 0644); e != nil {
		t.Fatal(e)
	}
}
