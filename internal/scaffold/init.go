package scaffold

import (
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/tankibaj/surfy/internal/detect"
	"github.com/tankibaj/surfy/internal/manifest"
)

type service struct {
	role, path, relative string
	fastapi              *fastAPI
}
type fastAPI struct {
	module, runner string
	envFile        bool
}

var fastAPIDeclaration = regexp.MustCompile(`(?m)^\s*app\s*=\s*FastAPI\s*\(`)

func Create(dir string) (string, error) {
	root, e := filepath.Abs(dir)
	if e != nil {
		return "", e
	}
	target := filepath.Join(root, "surfy.yaml")
	if _, e = os.Stat(target); e == nil {
		return "", errors.New("surfy.yaml already exists; it was not changed")
	} else if !errors.Is(e, os.ErrNotExist) {
		return "", e
	}
	web, e := discover(root, "web", []string{"frontend", "web", "client"})
	if e != nil {
		return "", e
	}
	api, e := discover(root, "api", []string{"backend", "api", "server"})
	if e != nil {
		return "", e
	}
	services := append(web, api...)
	if len(services) == 0 {
		rootServices, e := discoverRoot(root)
		if e != nil {
			return "", e
		}
		services = rootServices
	}
	if len(services) == 0 {
		return "", errors.New("unable to detect a supported application in the current directory")
	}
	content := render(services)
	f, e := os.OpenFile(target, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0644)
	if e != nil {
		if errors.Is(e, os.ErrExist) {
			return "", errors.New("surfy.yaml already exists; it was not changed")
		}
		return "", e
	}
	ok := false
	defer func() {
		if !ok {
			_ = os.Remove(target)
		}
	}()
	if n, writeErr := f.WriteString(content); writeErr != nil || n != len(content) {
		f.Close()
		if writeErr != nil {
			return "", writeErr
		}
		return "", io.ErrShortWrite
	}
	if e = f.Close(); e != nil {
		return "", e
	}
	ok = true
	return target, nil
}

func discover(root, role string, names []string) ([]service, error) {
	var found []service
	for _, name := range names {
		path := filepath.Join(root, name)
		if info, e := os.Stat(path); e != nil || !info.IsDir() {
			continue
		}
		svc := service{role: role, path: path, relative: "./" + name}
		if role == "api" {
			svc.fastapi = detectFastAPI(path)
		}
		if svc.fastapi != nil {
			found = append(found, svc)
			continue
		}
		if _, e := detect.Service(&manifest.Service{Path: path}, 49152); e == nil {
			found = append(found, svc)
		}
	}
	if len(found) > 1 {
		return nil, fmt.Errorf("multiple %s applications detected (%s); create surfy.yaml explicitly", role, joinPaths(found))
	}
	return found, nil
}

func discoverRoot(root string) ([]service, error) {
	var found []service
	if exists(root, "package.json") {
		if _, e := detect.Service(&manifest.Service{Path: root}, 49152); e == nil {
			found = append(found, service{role: "web", path: root, relative: "."})
		}
	}
	apiMarker := exists(root, "go.mod") || exists(root, "manage.py") || exists(root, "pyproject.toml") || exists(root, "requirements.txt") || exists(root, "Pipfile")
	if apiMarker {
		svc := service{role: "api", path: root, relative: ".", fastapi: detectFastAPI(root)}
		if svc.fastapi != nil {
			found = append(found, svc)
		} else if _, e := detect.Service(&manifest.Service{Path: root}, 49152); e == nil {
			found = append(found, svc)
		}
	}
	if len(found) > 1 {
		return nil, errors.New("both web and API runtimes were detected at the project root; create surfy.yaml explicitly")
	}
	return found, nil
}

func detectFastAPI(dir string) *fastAPI {
	for _, rel := range []string{"app/main.py", "main.py", "src/main.py"} {
		file := filepath.Join(dir, filepath.FromSlash(rel))
		b, e := os.ReadFile(file)
		if e != nil || !fastAPIDeclaration.Match(b) {
			continue
		}
		module := strings.TrimSuffix(strings.ReplaceAll(rel, "/", "."), ".py")
		runner := "python3 -m uvicorn"
		if info, e := os.Stat(filepath.Join(dir, ".venv", "bin", "uvicorn")); e == nil && info.Mode()&0111 != 0 {
			runner = "./.venv/bin/uvicorn"
		}
		return &fastAPI{module: module, runner: runner, envFile: exists(dir, ".env")}
	}
	return nil
}

func render(services []service) string {
	var b strings.Builder
	b.WriteString("# Generated by surfy init.\n# Paths are relative to this file.\n\n")
	for i, svc := range services {
		if i > 0 {
			b.WriteByte('\n')
		}
		if svc.role == "web" {
			b.WriteString("# Frontend application. Surfy assigns its internal port.\n")
		} else {
			b.WriteString("# Backend application. ${PORT} is assigned automatically.\n")
		}
		if svc.fastapi == nil {
			fmt.Fprintf(&b, "%s: %s\n", svc.role, svc.relative)
			continue
		}
		fmt.Fprintf(&b, "%s:\n  path: %s\n  run: %s %s:app --host 127.0.0.1 --port ${PORT} --reload\n", svc.role, svc.relative, svc.fastapi.runner, svc.fastapi.module)
		if svc.fastapi.envFile {
			b.WriteString("  env:\n    # Path is passed through; Surfy never reads this file.\n    ENV_FILE: ./.env\n")
		}
	}
	return b.String()
}
func exists(dir, name string) bool { _, e := os.Stat(filepath.Join(dir, name)); return e == nil }
func joinPaths(ss []service) string {
	p := make([]string, len(ss))
	for i, s := range ss {
		p[i] = s.relative
	}
	return strings.Join(p, ", ")
}
